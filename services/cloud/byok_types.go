// Cloud BYOK (docs/SECURITY/CLOUD_BYOK.md). A BYOK key is a KMS key whose
// material is imported into a cloud KMS: the cloud hands out an RSA
// wrapping key, keycore (or the HSM the key lives in) wraps the material to
// it, and the cloud unwraps it inside its own HSM. The KMS key is the source
// of truth; every piece of material the cloud holds is recorded against the
// KMS key version it came from (custody).

// Material sources.
const (
	SourceKMS = "kms" // generated by keycore's DRBG
	SourceHSM = "hsm" // generated in a PKCS#11 HSM with cloud import allowed
)

// Origins. A cloud-generated key was created in the cloud by a release
// before 10.0.0-beta (the cloud made the material); it is listed read-only.
const (
	OriginBYOK           = "byok"
	OriginCloudGenerated = "cloud-generated"
)

// Material states as the KMS records them.
const (
	MaterialPending  = "pending_import"
	MaterialCurrent  = "current"
	MaterialPrevious = "previous"
	MaterialRevoked  = "revoked"
	MaterialFailed   = "failed"
)

// KeySpec is the KMS's name for what a key is, mapped by each provider to
// its own key spec. Only these leave the KMS.
const (
	SpecAES256  = "AES-256"
	SpecHMAC256 = "HMAC-256"
	SpecRSA2048 = "RSA-2048"
	SpecRSA3072 = "RSA-3072"
	SpecRSA4096 = "RSA-4096"
	SpecECP256  = "EC-P256"
	SpecECP384  = "EC-P384"
)

// specFromKMS maps a keycore algorithm to a key spec; "" if none fits.
func specFromKMS(algorithm string) string {
	a := strings.ToUpper(strings.TrimSpace(algorithm))
	switch {
	case a == "AES-256" || strings.HasPrefix(a, "AES-256-") || a == "AES256":
		return SpecAES256
	case strings.HasPrefix(a, "HMAC") && strings.Contains(a, "256"):
		return SpecHMAC256
	case strings.HasPrefix(a, "RSA") && strings.Contains(a, "4096"):
		return SpecRSA4096
	case strings.HasPrefix(a, "RSA") && strings.Contains(a, "3072"):
		return SpecRSA3072
	case strings.HasPrefix(a, "RSA") && strings.Contains(a, "2048"):
		return SpecRSA2048
	case (strings.HasPrefix(a, "EC") || strings.Contains(a, "ECDSA")) && strings.Contains(a, "384"):
		return SpecECP384
	case (strings.HasPrefix(a, "EC") || strings.Contains(a, "ECDSA")) && strings.Contains(a, "256"):
		return SpecECP256
	}
	return ""
}

func specIsSymmetric(spec string) bool { return spec == SpecAES256 || spec == SpecHMAC256 }

// BYOKKey is a KMS key bound to a key in a cloud KMS.
type BYOKKey struct {
	ID          string `json:"id"`
	TenantID    string `json:"tenant_id"`
	AccountID   string `json:"account_id"`
	Provider    string `json:"provider"`
	Region      string `json:"region"`
	KeyID       string `json:"key_id"` // the KMS key
	Source      string `json:"source"`
	Origin      string `json:"origin"`
	KeySpec     string `json:"key_spec"`
	Usage       string `json:"usage"` // encrypt | sign | mac
	CloudKeyID  string `json:"cloud_key_id"`
	CloudKeyRef string `json:"cloud_key_ref"`
	Alias       string `json:"alias"`
	// CloudState is the cloud's own word for the key (Enabled,
	// PendingImport, ENABLED, ...), as last read.
	CloudState    string     `json:"cloud_state"`
	MaterialState string     `json:"material_state"`
	CurrentMatID  string     `json:"current_material_id"`
	// Settings are a provider's public parameters (Salesforce's BYOK
	// certificate and secret type). Never a credential.
	Settings map[string]string `json:"settings,omitempty"`
	ExpiresAt     *time.Time `json:"expires_at,omitempty"`
	CreatedBy     string     `json:"created_by"`
	CreatedAt     time.Time  `json:"created_at"`
	UpdatedAt     time.Time  `json:"updated_at"`
}

// BYOKMaterial is one import: which KMS key version is behind which cloud
// key material.
type BYOKMaterial struct {
	ID                string     `json:"id"`
	TenantID          string     `json:"tenant_id"`
	BYOKID            string     `json:"byok_id"`
	KMSVersion        int        `json:"kms_version"`
	KCV               string     `json:"kcv"`
	CloudMaterialID   string     `json:"cloud_material_id"`
	State             string     `json:"state"`
	Scheme            string     `json:"scheme"`
	Source            string     `json:"source"`
	WrappingKeySHA256 string     `json:"wrapping_key_sha256"`
	ImportedAt        time.Time  `json:"imported_at"`
	ExpiresAt         *time.Time `json:"expires_at,omitempty"`
	RevokedAt         *time.Time `json:"revoked_at,omitempty"`
}

// BYOKStep is one step of a run, with the cloud or KMS call it made and the
// equivalent command an operator would type.
type BYOKStep struct {
	Name       string    `json:"name"`
	Status     string    `json:"status"` // succeeded | failed | skipped
	Call       string    `json:"call,omitempty"`
	CLI        string    `json:"cli,omitempty"`
	Detail     string    `json:"detail,omitempty"`
	Error      string    `json:"error,omitempty"`
	StartedAt  time.Time `json:"started_at"`
	FinishedAt time.Time `json:"finished_at"`
}

// BYOKRun is one operation on a BYOK key and its steps.
type BYOKRun struct {
	ID         string     `json:"id"`
	TenantID   string     `json:"tenant_id"`
	BYOKID     string     `json:"byok_id"`
	Operation  string     `json:"operation"`
	Status     string     `json:"status"` // succeeded | failed
	Steps      []BYOKStep `json:"steps"`
	Actor      string     `json:"actor"`
	Error      string     `json:"error,omitempty"`
	StartedAt  time.Time  `json:"started_at"`
	FinishedAt time.Time  `json:"finished_at"`
}

// Operations.
const (
	OpCreate   = "create"   // create the cloud key and import the first material
	OpRotate   = "rotate"   // new KMS version, imported as new material, made current
	OpReimport = "reimport" // the same material again (renew expiry, repair)
	OpRevoke   = "revoke"   // kill switch: remove (or disable) the material in the cloud
	OpRestore  = "restore"  // bring revoked material back from the KMS
	OpVerify   = "verify"   // a cryptographic round trip in the cloud
	OpSync     = "sync"     // read the cloud key's state
)

type CreateBYOKRequest struct {
	AccountID    string `json:"account_id"`
	KeyID        string `json:"key_id"`
	Region       string `json:"region"`
	Alias        string `json:"alias"`
	Description  string `json:"description"`
	ValidityDays int    `json:"validity_days"` // 0: material does not expire
	// Salesforce Shield names its BYOK certificate and secret type here
	// (public data; the account's credential holds the access).
	CertificateName string `json:"certificate_name"`
	CertificatePEM  string `json:"certificate_pem"`
	SecretType      string `json:"secret_type"`
}

type BYOKOperationRequest struct {
	ValidityDays int    `json:"validity_days"`
	Reason       string `json:"reason"`
	// MaterialID picks the material for restore; empty is the last revoked.
	MaterialID string `json:"material_id"`
}

// Capabilities say which operations a cloud supports for imported
// material. The UI offers only these; the engine refuses the rest.
type Capabilities struct {
	Rotate         bool `json:"rotate"`
	Reimport       bool `json:"reimport"`
	Revoke         bool `json:"revoke"`
	RevokeDeletes  bool `json:"revoke_deletes"` // false: revoke disables
	Expiry         bool `json:"expiry"`
	Verify         bool `json:"verify"`
	Specs          []string `json:"specs"`
}

// cloudKeyCall is what a provider gets for every call.
type cloudKeyCall struct {
	Account     CloudAccount
	Credentials map[string]interface{}
	Region      string
}

// ImportParams are what the cloud hands out for one import.
type ImportParams struct {
	WrappingKey []byte
	Scheme         string // a pkg/crypto cloud wrapping scheme
	Token          []byte
	Handle         string // GCP import job, Azure KEK id, Salesforce certificate
	ValidTo        time.Time
	WantDigest     bool // Salesforce Shield takes SHA-256 of the material
}

type ImportRequest struct {
	Params       ImportParams
	Wrapped      []byte
	Digest       []byte
	NewMaterial  bool       // rotate: material the key has not had before
	Replace      string     // GCP: reimport into this version
	ExpiresAt    *time.Time // nil: does not expire
	Description  string
}

// BYOKProvider is one cloud's import protocol.
type BYOKProvider interface {
	Name() string
	Capabilities() Capabilities
	// CreateKey creates an empty key waiting for material, where the cloud
	// has one (AWS, Alibaba, GCP); others create the key on first import
	// and return it with only a name.
	CreateKey(ctx context.Context, c cloudKeyCall, k BYOKKey, description string) (BYOKKey, string, error)
	ImportParameters(ctx context.Context, c cloudKeyCall, k BYOKKey) (ImportParams, string, error)
	Import(ctx context.Context, c cloudKeyCall, k BYOKKey, in ImportRequest) (BYOKKey, string, string, error)
	// MakeCurrent makes newly imported material the key's current material
	// (AWS RotateKeyOnDemand, GCP primary version); "" when automatic.
	MakeCurrent(ctx context.Context, c cloudKeyCall, k BYOKKey, materialID string) (string, error)
	Revoke(ctx context.Context, c cloudKeyCall, k BYOKKey, materialID string) (string, error)
	// Unrevoke undoes a revoke the cloud can undo in place (re-enable);
	// ok=false means the material must be imported again.
	Unrevoke(ctx context.Context, c cloudKeyCall, k BYOKKey, materialID string) (bool, string, error)
	Describe(ctx context.Context, c cloudKeyCall, k BYOKKey) (BYOKKey, string, error)
	Verify(ctx context.Context, c cloudKeyCall, k BYOKKey) (string, string, error)
	// Cleanup removes what ImportParameters left in the cloud (Azure's
	// temporary key exchange key); "" when there is nothing.
	Cleanup(ctx context.Context, c cloudKeyCall, k BYOKKey, p ImportParams) (string, error)
}
