// BYOK automation (13.2.0-beta). A key's automation settings say when its
// cloud material should be renewed (N days before it expires) or rotated
// (every N days). The primary's sweep emits audit.cloud.byok_material_expiring
// and audit.cloud.byok_rotation_due once per piece of material; playbooks
// triggered by them run the BYOK actions (byok_reimport, byok_rotate) through
// the same routes a person uses. The sweep decides nothing itself.

const (
	settingRenewBefore   = "renew_before_days"
	settingRotateEvery   = "rotate_every_days"
	settingRenewFor      = "renew_validity_days"
	markExpiryNotified   = "_notified_expiry"
	markRotationNotified = "_notified_rotation"
)

// AutomationSettings are what a person sets; 0 turns a rule off.
type AutomationSettings struct {
	RenewBeforeDays   int `json:"renew_before_days"`
	RotateEveryDays   int `json:"rotate_every_days"`
	RenewValidityDays int `json:"renew_validity_days"`
}

func automationOf(k BYOKKey) AutomationSettings {
	n := func(name string) int { v, _ := strconv.Atoi(k.Settings[name]); return v }
	return AutomationSettings{RenewBeforeDays: n(settingRenewBefore), RotateEveryDays: n(settingRotateEvery), RenewValidityDays: n(settingRenewFor)}
}

// SetAuditEmitter wires the audit client for events no request carries.
func (s *Service) SetAuditEmitter(e route.Emitter) { s.audit = e }

// SetBYOKAutomation saves a key's automation rules, refusing a rule its
// cloud can't act on.
func (s *Service) SetBYOKAutomation(ctx context.Context, tenantID, id string, in AutomationSettings) (BYOKKey, error) {
	t, err := s.byokTarget(ctx, tenantID, id)
	if err != nil {
		return BYOKKey{}, err
	}
	if t.key.Origin != OriginBYOK {
		return t.key, refuseBYOK(http.StatusConflict, "cloud_generated", "this key's material was generated by the cloud")
	}
	caps := t.provider.Capabilities()
	for name, v := range map[string]int{settingRenewBefore: in.RenewBeforeDays, settingRotateEvery: in.RotateEveryDays, settingRenewFor: in.RenewValidityDays} {
		if v < 0 || v > 3650 {
			return t.key, refuseBYOK(http.StatusBadRequest, "bad_request", name+" must be between 0 and 3650")
		}
	}
	if (in.RenewBeforeDays > 0 || in.RenewValidityDays > 0) && !caps.Expiry {
		return t.key, refuseBYOK(http.StatusConflict, "operation_not_supported", cloudName(t.key.Provider)+" has no expiry to renew")
	}
	if in.RenewValidityDays > 365 || in.RenewBeforeDays > 365 {
		return t.key, refuseBYOK(http.StatusBadRequest, "bad_request", "imported material can be valid for at most 365 days, so renewal windows are too")
	}
	if in.RenewBeforeDays > 0 && in.RenewValidityDays == 0 {
		// Renewing with no validity would re-import the material as
		// never expiring.
		return t.key, refuseBYOK(http.StatusBadRequest, "bad_request", "renew_validity_days is required with renew_before_days")
	}
	if in.RotateEveryDays > 0 && !caps.Rotate {
		return t.key, refuseBYOK(http.StatusConflict, "operation_not_supported", cloudName(t.key.Provider)+" can't take new material on a key")
	}
	if t.key.Settings == nil {
		t.key.Settings = map[string]string{}
	}
	for name, v := range map[string]int{settingRenewBefore: in.RenewBeforeDays, settingRotateEvery: in.RotateEveryDays, settingRenewFor: in.RenewValidityDays} {
		if v == 0 {
			delete(t.key.Settings, name)
		} else {
			t.key.Settings[name] = strconv.Itoa(v)
		}
	}
	return t.key, s.byokStore.UpdateBYOKKey(ctx, t.key)
}

// sweepBYOKAutomation emits the due events, once per material, and returns
// how many it emitted.
func (s *Service) sweepBYOKAutomation(ctx context.Context, now time.Time) (int, error) {
	if s.byokStore == nil {
		return 0, nil
	}
	keys, err := s.byokStore.ListAutomatedBYOKKeys(ctx)
	if err != nil {
		return 0, err
	}
	emitted := 0
	for _, k := range keys {
		a := automationOf(k)
		if k.Origin != OriginBYOK || k.MaterialState != MaterialCurrent {
			continue
		}
		changed := false
		if a.RenewBeforeDays > 0 && k.ExpiresAt != nil {
			mark := fmt.Sprintf("%s@%d", k.CurrentMatID, k.ExpiresAt.Unix())
			left := k.ExpiresAt.Sub(now)
			if left <= time.Duration(a.RenewBeforeDays)*24*time.Hour && k.Settings[markExpiryNotified] != mark {
				s.emitAutomation(ctx, "byok_material_expiring", k, map[string]interface{}{
					"expires_at": k.ExpiresAt.UTC().Format(time.RFC3339), "days_left": int(math.Floor(left.Hours() / 24)),
					"renew_before_days": a.RenewBeforeDays, "validity_days": a.RenewValidityDays,
				})
				k.Settings[markExpiryNotified], changed = mark, true
				emitted++
			}
		}
		if a.RotateEveryDays > 0 && k.Settings[markRotationNotified] != k.CurrentMatID {
			_, current := s.materials(ctx, k)
			if current.ID != "" && now.Sub(current.ImportedAt) >= time.Duration(a.RotateEveryDays)*24*time.Hour {
				s.emitAutomation(ctx, "byok_rotation_due", k, map[string]interface{}{
					"material_imported_at": current.ImportedAt.UTC().Format(time.RFC3339), "kms_version": current.KMSVersion,
					"material_age_days": int(now.Sub(current.ImportedAt).Hours() / 24), "rotate_every_days": a.RotateEveryDays,
				})
				k.Settings[markRotationNotified], changed = k.CurrentMatID, true
				emitted++
			}
		}
		if changed {
			if err := s.byokStore.UpdateBYOKKey(ctx, k); err != nil {
				return emitted, err
			}
		}
	}
	return emitted, nil
}

func (s *Service) emitAutomation(ctx context.Context, action string, k BYOKKey, details map[string]interface{}) {
	if s.audit == nil {
		return
	}
	details["key_id"], details["provider"], details["account_id"] = k.KeyID, k.Provider, k.AccountID
	details["cloud_key_id"], details["material_id"], details["severity"] = k.CloudKeyID, k.CurrentMatID, "warning"
	_ = s.audit.Emit(ctx, action, pkgaudit.Event{
		TenantID: k.TenantID, ActorID: "kms-cloud", ActorType: "service", TargetType: "cloud_byok_key", TargetID: k.ID,
		Result: route.ResultSuccess, Details: details,
	})
}

// byokAutomationLoop sweeps on the primary only: the sweep writes the
// replicated notification marks (docs/CLUSTERING.md).
func (s *Service) byokAutomationLoop(ctx context.Context, primary func(context.Context) bool, every time.Duration, logf func(string, ...interface{})) {
	t := time.NewTicker(every)
	defer t.Stop()
	for {
		if primary(ctx) {
			if _, err := s.sweepBYOKAutomation(ctx, time.Now().UTC()); err != nil {
				logf("byok automation sweep: %v", err)
			}
		}
		select {
		case <-ctx.Done():
			return
		case <-t.C:
		}
	}
}

func (h *Handler) setBYOKAutomation(c *route.Call) {
	var in AutomationSettings
	if !c.Decode(&in) {
		return
	}
	c.Detail(settingRenewBefore, in.RenewBeforeDays)
	c.Detail(settingRotateEvery, in.RotateEveryDays)
	c.Detail(settingRenewFor, in.RenewValidityDays)
	k, err := h.svc.SetBYOKAutomation(c.R.Context(), c.Tenant, c.R.PathValue("id"), in)
	if err != nil {
		h.byokFail(c, BYOKRun{}, k, err)
		return
	}
	c.JSON(http.StatusOK, map[string]interface{}{"key": k, "automation": automationOf(k)})
}
